def refuse(code):
    raise WorldlineError(code, 'protected recovery observation or handoff is unestablished')


def pairs(rows):
    result={}
    for key,value in rows:
        if key in result: refuse('RECOVERY_DUPLICATE_FIELD')
        result[key]=value
    return result


def private_bytes(path):
    """Complete bytes; no new history-size truncation or selected-row projection."""
    from intent_gate import protected
    path=Path(path); protected(path,private=True)
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_CLOEXEC|os.O_NONBLOCK)
    try:
        before=os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or before.st_uid!=0 or before.st_nlink!=1:
            refuse('RECOVERY_PROTECTED_FILE_SHAPE')
        with os.fdopen(os.dup(fd),'rb') as file: raw=file.read()
        after=os.fstat(fd)
        if ((before.st_dev,before.st_ino,before.st_size,before.st_mtime_ns,before.st_ctime_ns)!=
            (after.st_dev,after.st_ino,after.st_size,after.st_mtime_ns,after.st_ctime_ns)
            or len(raw)!=before.st_size): refuse('RECOVERY_PROTECTED_FILE_CHANGED')
        return raw
    finally: os.close(fd)


def exact_json(raw):
    value=json.loads(raw,object_pairs_hook=pairs)
    if raw not in (canonical_bytes(value),canonical_bytes(value)+b'\n'): refuse('RECOVERY_NONCANONICAL_JSON')
    return value


def identity(value):
    return hashlib.sha256(archive(value)).digest()


class ProtectedCapture:
    def __init__(self,gate,controller,*,startup_lease):
        from intent_gate import Gate, protected
        if os.geteuid()!=0 or type(gate) is not Gate or type(controller) is not RuntimeController:
            refuse('RECOVERY_PROTECTED_PRINCIPAL_REQUIRED')
        if type(controller.core) is not Core or type(controller.transactions) is not CollapseTransaction:
            refuse('RECOVERY_ORIGINAL_NATIVE_PRODUCERS_REQUIRED')
        if controller.transactions.core is not controller.core or controller.store.core is not controller.core:
            refuse('RECOVERY_NATIVE_PRODUCER_IDENTITY')
        self.gate,self.controller,self.tx,self.core=gate,controller,controller.transactions,controller.core
        if gate.issuer is None or gate.universe is None or gate.ledger_socket is None:
            refuse('RECOVERY_PROTECTED_HEADS_UNAVAILABLE')
        # This file is installed/approved by the operator, never generated by a
        # daemon request. Presence is not sufficient: exact paths and source
        # inventory are checked against this actual process below.
        conf=exact_json(private_bytes(gate.root/'authority/gate/recovery-bind.json'))
        expected={'schema','store_data','store_state','worldline_source','worldline_inventory','kernel_build'}
        if type(conf) is not dict or set(conf)!=expected or conf['schema']!='worldline.protected-recovery-bind-v1':
            refuse('RECOVERY_PROTECTED_BIND_SCHEMA')
        if conf['store_data']!=str(controller.paths.data) or conf['store_state']!=str(controller.paths.state):
            refuse('RECOVERY_PROTECTED_STORE_BINDING')
        for path in (controller.paths.data,controller.paths.state,controller.paths.config):
            protected(path,directory=True,private=True)
        self.conf=conf
        self._check_source()
        # The exact lease was acquired before StateStore/Controller construction.
        # A late lock or duck-typed caller claim cannot establish that ordering.
        from .protected_startup import StartupLease
        if type(startup_lease) is not StartupLease:
            refuse('RECOVERY_PROTECTED_STARTUP_LEASE_REQUIRED')
        startup_lease.intact()
        if Path(startup_lease.state_path)!=controller.paths.state:
            refuse('RECOVERY_STARTUP_STORE_PATH_CHANGED')
        self.startup_lease=startup_lease
        self.store_lock=startup_lease.store_lock_fd
        if not store_lock_intact(controller.paths.state,self.store_lock):
            refuse('RECOVERY_STARTUP_STORE_LOCK_CHANGED')
        self.use_reservations=None
        self.mapping=self.kernel_material()

    def _check_source(self):
        from intent_gate import protected
        root=Path(self.conf['worldline_source']); protected(root,directory=True)
        inventory=exact_json(private_bytes(self.conf['worldline_inventory']))
        if type(inventory) is not dict: refuse('RECOVERY_PROTECTED_SOURCE_INVENTORY')
        actual={}
        for path in sorted(root.rglob('*')):
            if path.is_symlink(): refuse('RECOVERY_SOURCE_SYMLINK')
            if path.is_file():
                protected(path)
                actual[path.relative_to(root).as_posix()]={
                    'mode':oct(stat.S_IMODE(path.stat().st_mode)),
                    'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
        if actual!=inventory: refuse('RECOVERY_PROTECTED_SOURCE_CHANGED')
        if Path(__file__).resolve()!=root/'runtime/worldline/protected_recovery_capture.py':
            refuse('RECOVERY_SOURCE_PROCESS_UNBOUND')
        if Path(CollapseTransaction._observe_authorization.__code__.co_filename).resolve()!=root/'runtime/worldline/transaction.py':
            refuse('RECOVERY_PACKET_PRODUCER_PROCESS_UNBOUND')
        self.source_inventory_raw=private_bytes(self.conf['worldline_inventory'])

    def intact(self):
        self.startup_lease.intact()
        if not store_lock_intact(self.controller.paths.state,self.store_lock):
            refuse('RECOVERY_ACTUATOR_STORE_LOCK_CHANGED')
        self._check_source()
        if self.kernel_material()!=self.mapping: refuse('RECOVERY_EXACT_NATIVE_MAPPING_CHANGED')

    def kernel_material(self):
        """Measure actual mapped file descriptors and native function locations.

        /proc map text alone is insufficient. map_files descriptors, inode,
        contents, executable ranges and actual native symbol addresses must all
        agree with the protected selected library. Restart can change addresses;
        the retained logical identity excludes load-address relocation only.
        """
        from intent_gate import protected
        if self.core.library_source=='environment': refuse('RECOVERY_ENVIRONMENT_NATIVE_LIBRARY')
        library=Path(self.core.library_path); protected(library)
        raw=library.read_bytes(); info=library.stat()
        build=private_bytes(self.conf['kernel_build'])
        segments=[]; ranges=[]
        for line in Path('/proc/self/maps').read_text().splitlines():
            fields=line.split(maxsplit=5)
            if len(fields)!=6 or fields[5]!=str(library): continue
            bounds,permissions,offset,device,inode,_path=fields
            start,end=(int(value,16) for value in bounds.split('-'))
            mapped=Path('/proc/self/map_files')/bounds
            try: fd=os.open(mapped,os.O_RDONLY|os.O_CLOEXEC)
            except OSError: refuse('RECOVERY_MAPPED_DESCRIPTOR_UNAVAILABLE')
            try:
                measured=os.fstat(fd)
                with os.fdopen(os.dup(fd),'rb') as stream: contents=stream.read()
                if (measured.st_dev,measured.st_ino)!=(info.st_dev,info.st_ino) or contents!=raw:
                    refuse('RECOVERY_MAPPED_DESCRIPTOR_DIFFERS')
            finally: os.close(fd)
            segments.append({'permissions':permissions,'offset':offset,'device':device,'inode':inode,
                             'mapped_length':end-start})
            ranges.append((start,end,permissions))
        if not segments: refuse('RECOVERY_NATIVE_MAPPING_ABSENT')
        symbols=('wl_collapse_decide_raw_evaluation_v3','wl_recovery_authorization_decide_v3',
                 'wl_recovery_protocol_decide_v1')
        for name in symbols:
            try: address=C.cast(getattr(self.core._lib,name),C.c_void_p).value
            except AttributeError: refuse('RECOVERY_EXACT_NATIVE_ABI_UNAVAILABLE')
            if address is None or not any(start<=address<end and 'x' in perms for start,end,perms in ranges):
                refuse('RECOVERY_NATIVE_SYMBOL_MAPPING_DIFFERS')
        after=library.stat()
        if (info.st_dev,info.st_ino,info.st_size,info.st_ctime_ns,info.st_mtime_ns)!=(
                after.st_dev,after.st_ino,after.st_size,after.st_ctime_ns,after.st_mtime_ns):
            refuse('RECOVERY_NATIVE_LIBRARY_CHANGED')
        return {'library_path':os.fsencode(library),'device':info.st_dev,'inode':info.st_ino,
                'library_bytes':raw,'segments':segments,'symbols':symbols,'build_bytes':build}

    def mapping_material(self,path):
        from intent_gate import protected
        path=Path(path); protected(path.parent,directory=True,private=True)
        before=path.lstat()
        if not stat.S_ISLNK(before.st_mode) or before.st_uid!=0:
            refuse('RECOVERY_MAPPING_NOT_PROTECTED_SYMLINK')
        raw=os.readlink(os.fsencode(path)); target=path.resolve(strict=True)
        protected(target,directory=True,private=True)
        if not target.is_relative_to(self.controller.paths.data): refuse('RECOVERY_MAPPING_OUTSIDE_STORE')
        after=path.lstat()
        if (before.st_dev,before.st_ino,before.st_ctime_ns)!=(after.st_dev,after.st_ino,after.st_ctime_ns):
            refuse('RECOVERY_MAPPING_CHANGED_DURING_CAPTURE')
        return {'target':os.fsencode(target),'raw_link':raw,'device':before.st_dev,'inode':before.st_ino}

    def chain_material(self):
        store=self.controller.store; store.verify_chains()
        result={}
        with store._lock:
            for table,kind in (('causal_events','events'),('receipts','receipts')):
                rows=store._connection.execute('SELECT * FROM '+table+' ORDER BY rowid').fetchall()
                result[kind]=[(dict(row),store.read_canonical(kind,row['canonical_path'],chain_hash=row['chain_hash'])) for row in rows]
        return result

    def capture(self,pending,peer,transaction_id,*,flush=False):
        self.intact(); tx=self.tx; record=tx._load_record(transaction_id)
        if record['state'] not in ('PREPARED','AUTHORIZED'): refuse('RECOVERY_TRANSACTION_NOT_CLAIMABLE')
        tx._pre_exchange_guards(transaction_id)
        candidate=tx.store.world(record['candidateWorld']); tx.stop_writers(candidate)
        generation=tx._generation()
        if flush: tx._fsync_payload_tree(Path(record['stagingPayload']))
        current=tx._capture_current_roots(); staged=tx._capture_staged(record)
        if Manifest.root_set_hash(current.values(),self.core)!=record['beforeRoot']:
            refuse('RECOVERY_BEFORE_PAYLOAD_CHANGED')
        candidate_now={root['root_key']:tx._capture_payload(
            source=os.fsencode(Path(candidate.payload_path)/root['root_key']),logical=bytes(root['path']),root=root)
            for root in tx.store.roots()}
        if Manifest.root_set_hash(candidate_now.values(),self.core)!=record['candidateRoot']:
            refuse('RECOVERY_CANDIDATE_PAYLOAD_CHANGED')
        requirement=current_requirements(tx.store,tx.config,self.core)
        decision,observed=tx._observe_authorization(record,candidate,current_manifests=current,
            staged_root=Manifest.root_set_hash(staged.values(),self.core),
            staged_content_root=content_root_set(staged,self.core),current_requirement=requirement,generation_before=generation)
        if decision!='AUTHORIZED': refuse('RECOVERY_FRESH_NATIVE_'+decision)
        if tx._checkpoint_collision(record,candidate,staged) is not None:
            refuse('RECOVERY_CHECKPOINT_IDENTITY_TAKEN')
        if type(observed.packet) is not bytes: refuse('RECOVERY_FULL_PACKET_ABSENT')
        packet=restore_archive(observed.packet); values=observed.values
        native=self.kernel_material(); before=self.mapping_material(tx.paths.live)
        after=self.mapping_material(record['preparedMapping']); chains=self.chain_material()
        facts=self.gate.facts(); universe=self.gate.universe.read(); issuer=self.gate.issuer.head()
        capability=pending['capability']; reservation=pending['resource']['reservation']
        if peer['uid']!=self.gate.config['requester_uid'] or pending['op']!='promote': refuse('RECOVERY_PEER_OPERATION_UNBOUND')
        use={'capability_id':capability['capability_id'],'operation_id':pending['operation_id'],
             'transaction_id':transaction_id,'action':capability['request']['action'],
             'universe_head':pending['universe_event_head'],
             'policy_epoch':self.gate.issuer.policy['root_grant']['policy_epoch']}
        from .recovery_authority_kernel_v3 import BoundUse,binding_record
        selected=(packet['primary'],packet['staged'])
        if all(value is None for value in selected): refuse('RECOVERY_SELECTED_EVALUATION_ABSENT')
        mode=('CHECKPOINT_RETURN' if values.mode=='CHECKPOINT_RETURN' else
              ('STAGED' if packet['staged'] is not None else 'CANDIDATE') if values.mode=='CANDIDATE_EVALUATION' else None)
        if mode is None: refuse('RECOVERY_MODE_UNESTABLISHED')
        bound=BoundUse(mode=mode,operation=bytes.fromhex(pending['operation_id']),transaction=identity(transaction_id),
            capability=bytes.fromhex(capability['capability_id']),universe_head=bytes.fromhex(universe['event_head']),
            instance=identity(candidate.instance_id),subject=values.expected_subject,staged_root=values.actual_staged_root,
            current_requirement=values.current_requirement,resulting_requirement=values.resulting_requirement,
            requester=identity({'uid':peer['uid'],'gid':peer['gid']}),grant_use=identity(use),
            policy_identity=bytes.fromhex(self.gate.issuer.policy_sha256),selected_evaluation=identity(selected),
            history_head=identity(tuple(value['authorityMaterial'] if value is not None else None for value in selected)),
            reservation=identity(reservation),host=identity({'boot':Path('/proc/sys/kernel/random/boot_id').read_bytes(),
              'machine':Path('/etc/machine-id').read_bytes()}),before_prime=identity(tx.store.prime()),
            before_root=hash_bytes_from_id(record['beforeRoot']),before_mapping=identity(before['target']),
            staged_mapping=identity(after['target']),input_snapshot=hashlib.sha256(observed.packet).digest(),
            kernel_build=hashlib.sha256(native['build_bytes']).digest(),kernel_library=hashlib.sha256(native['library_bytes']).digest(),
            kernel_mapping=identity(native),issuer_head=bytes.fromhex(issuer['event_head']),
            receipt_head=identity(chains['receipts']),causal_head=identity(chains['events']),
            policy_epoch=universe['record']['policy_epoch'],resource_epoch=facts['binding']['resource_generation'])
        result={'binding':binding_record(bound),'packet':observed.packet,'record':record,'peer':peer,
                'pending':restore_archive(archive(pending)),'native':native,'before_mapping':before,'staged_mapping':after,
                'chains':chains,'capability_use':use,'current_requirement':requirement,'staged_manifests':[
                    (key,{'value':value.value,'canonical':value.canonical,'root_hash':value.root_hash}) for key,value in staged.items()]}
        if packet.get('owner') is not None:
            from .protected_owner import installed_owner
            result['owner_binding']=installed_owner(self.controller).recovery_binding(result)
        return result

    def historical(self,capture):
        self.intact()
        if capture['native']!=self.kernel_material(): refuse('RECOVERY_HISTORICAL_NATIVE_MAPPING_UNAVAILABLE')
        from .recovery_authority_kernel_v3 import restore_binding
        binding=restore_binding(capture['binding'])
        if hashlib.sha256(capture['packet']).digest()!=binding.input_snapshot:
            refuse('RECOVERY_HISTORICAL_PACKET_BINDING_DIFFERS')
        if redecide_packet(capture['packet'],core=self.core)!='AUTHORIZED':
            refuse('RECOVERY_HISTORICAL_NATIVE_DENIED')
        return binding

    def observe_effect(self):
        self.intact()
        from .recovery_authority_kernel_v3 import NativeObservation
        mapping=self.mapping_material(self.tx.paths.live)
        manifests=self.tx._capture_current_roots()
        root=hash_bytes_from_id(Manifest.root_set_hash(manifests.values(),self.core))
        return NativeObservation(live_mapping=identity(mapping['target']),live_root=root), {'mapping':mapping,'root':root}

    def claim_capability_use(self,capture):
        from .protected_capability_uses import ProtectedUseReservations
        if type(self.use_reservations) is not ProtectedUseReservations:
            refuse('RECOVERY_NATIVE_CAPABILITY_USE_RESERVATION_UNAVAILABLE')
        return self.use_reservations.reserve(capture)

    def dispatch(self,capture):
        """Only this protected call owns the original atomic exchange.

        Caller must have durably recorded Effect_Intent and the proved capability
        use reservation. This method cannot be reached through an IPC flag.
        """
        self.intact(); tx=self.tx; record=tx._load_record(capture['record']['transactionId'])
        import recovery_principal
        principal=getattr(self,'principal',None)
        if type(principal) is not recovery_principal.ProtectedRecoveryPrincipal or principal.capture is not self:
            refuse('RECOVERY_ACTUAL_DISPATCH_PRINCIPAL_REQUIRED')
        operation=capture['pending']['operation_id'];row=principal.journal.latest.get(operation)
        if principal.journal.poisoned or row is None or row['state']!='EFFECT_INTENT':
            refuse('RECOVERY_DURABLE_EFFECT_INTENT_REQUIRED')
        issued=principal._boundary(row,'EFFECT_INTENT')
        reserved=principal._boundary(row,'FINAL_CAPABILITY_RESERVATION_ACK')
        if issued['fresh_packet']!=capture['packet'] or issued['fresh_native']!=capture['native'] or reserved['reservation']['status']!='RESERVED_REPLAY':
            refuse('RECOVERY_ACTUAL_DISPATCH_BINDING_CHANGED')
        if capture.get('owner_binding') is not None:
            from .protected_owner import installed_owner
            installed_owner(self.controller).begin_collapse(capture)
        if record['state']!='PREPARED': refuse('RECOVERY_EXCHANGE_STATE_UNESTABLISHED')
        tx._set_state(record,'AUTHORIZED')
        record['decisionInputsAtCommit']=capture['record']['decisionInputsAtCommit']
        record['commitRequirementHash']=capture['current_requirement']['requirementHash']
        record['commitIntent']={'state':'COMMITTING','transactionId':record['transactionId'],'stagedRoot':record['stagedRoot']}
        atomic_write_json(Path(record['preparedPath']),record)
        decided=restore_archive(capture['packet'])['values'].generation_after
        if decided is None or tx._generation()!=decided or tx.watcher is None:
            refuse('RECOVERY_PRE_EXCHANGE_GENERATION_CHANGED')
        with tx.watcher.owned_writes(): tx.atomic.exchange(tx.paths.live,Path(record['preparedMapping']))

    def finish_receipt(self,capture):
        self.historical(capture)
        tx=self.tx; record=tx._load_record(capture['record']['transactionId'])
        if record['state'] not in ('AUTHORIZED','COMMITTED'): refuse('RECOVERY_SETTLEMENT_TRANSACTION_STATE')
        manifests={}
        for key,row in capture['staged_manifests']:
            if canonical_bytes(row['value'])!=row['canonical'] or hash_id(self.core.hash_bytes(
                    b'worldline-manifest-v1'+row['canonical']))!=row['root_hash']:
                refuse('RECOVERY_HISTORICAL_MANIFEST_CHANGED')
            if key in manifests: refuse('RECOVERY_DUPLICATE_HISTORICAL_ROOT')
            manifests[key]=CapturedManifest(**row)
        # Full original historical manifests, never today's policy/tree as a
        # replacement for the tree to which the established effect committed.
        if Manifest.root_set_hash(manifests.values(),self.core)!=record['stagedRoot']:
            refuse('RECOVERY_HISTORICAL_MANIFEST_ROOT')
        return tx._finish_committed(record,manifests)

    def owner_resolution(self,peer,record,request):
        # No existing protected capability action binds K4's owner resolution,
        # exact quarantine head, operation and replacement observations. Root
        # UID or a request Boolean alone never clears durable quarantine.
        refuse('RECOVERY_PROTECTED_OWNER_RESOLUTION_UNAVAILABLE')
