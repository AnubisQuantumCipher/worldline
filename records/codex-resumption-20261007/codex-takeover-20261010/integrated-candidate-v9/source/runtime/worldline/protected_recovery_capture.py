"""Root-principal capture using the actual Controller/store/transaction producers.

No packet, Boolean verdict, native handle, binding or mapping supplied over IPC is
accepted here. Bootstrap must bind this source, controller and store to protected
installed state before exposing the principal. The current lab has no such
bootstrap record: absence refuses, and is an OPEN integration obligation.
"""
